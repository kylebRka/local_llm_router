def build_records():
    records = []
    for label, pools in DATA.items():
        assert len(pools) == 5
        for pool_index, (category, difficulty, items, templates) in enumerate(pools):
            assert len(items) == len(set(items)) == 20
            assert len(templates) == 5
            for item_index, item in enumerate(items):
                family = f"{label}-{pool_index}-{item_index}"
                for template in templates:
                    records.append({
                        "text": template.format(item=item),
                        "label": label,
                        "category": category,
                        "difficulty": difficulty,
                        "family": family,
                    })
    assert len(records) == 1500
    normalized = [r["text"].casefold().strip() for r in records]
    assert len(normalized) == len(set(normalized)), "Duplicate requests"
    return records


def main():
    DATA_PATH.parent.mkdir(parents=True, exist_ok=True)
    with DATA_PATH.open("w", encoding="utf-8") as file:
        for record in build_records():
            file.write(json.dumps(record, ensure_ascii=False) + "\n")
    print(f"Saved / Сохранено {len(build_records())} requests / запросов: {DATA_PATH}")


if __name__ == "__main__":
    main()
